# print vertical output [range(start,end,skip)]
for i in range(1,6,1):
  for j in range(1,6,1):
    print(i)

# print convert vertical output to horizontal output
for i in range(1,6,1):
  for j in range(1,6,1):
    print(i, end = " ")

# print shape shape output with *
for i in range(1,6,1):
  for j in range(1,6,1):
    print("*" , end = " ")
  print("\r")

